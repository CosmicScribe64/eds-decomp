def _hex(x):
    m = re.match(r'\s*(0x[0-9A-Fa-f]+|\d+)', str(x))
    return int(m.group(1), 0) if m else None


def field_size(ftype, S):
    """Byte size of a non-bitfield member type string, or None when unknown (agbcc: structs padded to 4)."""
    t = re.sub(r'\s*\((?![^()]*\*)[^()]*\)\s*$', '', ftype).strip()
    if '(*' in t or '( *' in t:                     # pointer to array / function
        return 4
    dims = [d for d in re.findall(r'\[([^\]]*)\]', t)]
    base = re.sub(r'\[[^\]]*\]', '', t).strip()
    n = 1
    for d in dims:
        v = _hex(d)
        if v is None:
            return None
        n *= v
    if '*' in base or '(' in base:
        return 4 * n
    m = re.match(r'^(?:const\s+|volatile\s+)*(struct|union)\s+(\w+)$', base)
    if m:
        st = S.get(m.group(2))
        sz = _hex(st['size']) if st else None
        return None if sz is None else -(-sz // 4) * 4 * n
    base = re.sub(r'^(const|volatile)\s+', '', base)
    base = re.sub(r'\s*\(enum \w+\)$', '', base).strip()
    sz = SCALAR_SIZE.get(base.split()[0] if base else '')
    return None if sz is None else sz * n


def layout_warnings(name, size, fields, S):
    """Overlaps between consecutive members (a union or a view is needed) and by-value structs that agbcc pads
    to 4 bytes but the next member starts sooner."""
    out = []
    rows = []
    for f in fields:
        if f.get('bits'):
            continue
        off = _hex(f['offset'])
        if off is None:
            continue
        rows.append((off, f))
    rows.sort(key=lambda r: r[0])
    total = _hex(size)
    rng = re.search(r'\((0x[0-9A-Fa-f]+)\.\.(0x[0-9A-Fa-f]+)\)', str(size))
    if rng:                                          # union member documented with gSceneWork-based offsets
        total = int(rng.group(2), 16)
    for i, (off, f) in enumerate(rows):
        sz = field_size(f['type'], S)
        if sz is None:
            continue
        nxt = next((o for o, _ in rows[i + 1:] if o > off), total)
        if nxt is not None and off + sz > nxt:
            kind = 'padded struct' if re.search(r'\bstruct\b', f['type']) and '*' not in f['type'] else 'member'
            out.append(f"{f['name']} (+0x{off:X}, {f['type']}) is {sz:#x} bytes ({kind}) but the next member starts "
                       f"at +0x{nxt:X}: needs a union, a smaller type or an unpadded view")
    return out


# ----------------------------------------------------------------------------------------------- legacy renames

def legacy_renames(types_structs):
    """Map legacy include/*.h (or include/legacy/*.h) field names to types.json names by bit offset."""
    try:
        import structmap
        from pycparser import c_parser
    except ImportError:
        return {}, 'pycparser not available (run under tools/dr)'
    res = {}
    base = 'include/legacy' if os.path.isdir('include/legacy') else 'include'
    for hdr in ('main.h', 'duel.h', 'duel_ui.h', 'sound.h'):
        path = os.path.join(base, hdr)
        if not os.path.exists(path):
            continue
        import genprotos as gp
        text = gp.strip_attrs(gp.fold_asm(gp.strip_bodies(gp.clean(gp.cpp(path)))[0]))   # keeps line markers
        ast = c_parser.CParser().parse(text, path)
        lay = structmap.Layout(ast)
        for (_kind, tag), body in lay.structs.items():
            if tag not in types_structs:
                continue
            if body.coord and os.path.basename(str(body.coord.file)) != hdr:
                continue                      # defined by an included header (duel_ui.h includes duel.h)
            fields = {}
            for f in types_structs[tag]['fields']:
                try:
                    off = int(f['offset'], 16)
                except ValueError:
                    continue
                b = f.get('bits')
                if b:
                    lo = int(str(b).split('-')[0])
                    hi = int(str(b).split('-')[-1])
                    fields[(off * 8 + lo, hi - lo + 1)] = f['name']
                else:
                    fields[(off * 8, None)] = f['name']
            ren = {}
            for name, bit, w, size, ty in lay.members(body)[0]:
                key = (bit, w)
                new = fields.get(key)
                if new and new != name:
                    ren[name] = new
            res[tag] = {'legacy_header': f'include/legacy/{hdr}', 'renames': ren}
    return res, None


