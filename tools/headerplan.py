def sub_key(title):
    for prefix, key in SUBSYSTEMS:
        if title.startswith(prefix):
            return key
    raise ValueError(f'unknown subsystem section: {title}')


def load_final():
    """-> {name: {addr, sub, kind (functions|ram|rom), summary, confidence}}"""
    out, sec, kind = {}, None, None
    for line in open('build/names/final.txt'):
        if line.startswith('## '):
            sec = sub_key(line[3:].strip())
            continue
        if line.startswith('### '):
            k = line[4:].split('(')[0].strip()
            kind = {'functions': 'function', 'RAM globals': 'ram', 'ROM data': 'rom'}[k]
            continue
        m = re.match(r'(0x[0-9A-Fa-f]+) (\S+)\s*(?:#\s*(.*?))?\s*(?:\[(high|medium|low)\])?\s*$', line.rstrip('\n'))
        if m and sec and sec != 'alias':
            out[m.group(2)] = {'addr': m.group(1), 'sub': sec, 'kind': kind, 'summary': (m.group(3) or '').strip(),
                               'confidence': m.group(4)}
    return out


