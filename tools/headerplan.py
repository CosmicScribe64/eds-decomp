def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--out', default=OUT)
    ap.add_argument('--header')
    ap.add_argument('--owner')
    a = ap.parse_args()
    if a.header or a.owner:
        plan = json.load(open(a.out))
        if a.header:
            print(json.dumps(plan['headers'][a.header], indent=1))
        else:
            print(plan['owners'].get(a.owner, f'{a.owner}: not in the plan'))
        return
    plan = build()
    os.makedirs(os.path.dirname(a.out), exist_ok=True)
    json.dump(plan, open(a.out, 'w'), indent=1)
    summary(plan)
    print(f'wrote {a.out}')


def build():
    old2new = load_old2new()
    types = json.load(open('build/names/types.json'))
    protos_prop = {f['name']: f for f in json.load(open('build/names/prototypes.json'))['functions']}
    pdb = json.load(open('build/readability/protos.json'))
    final = load_final()
    funcs = load_functions()
    S = {s['name']: s for s in types['structs']}
    E = {e['name']: e for e in types['enums']}
    errors = []

    # every header
    H = {}
    for path, (group, desc) in HEADERS.items():
        H[path] = {'path': f'include/{path}', 'group': group, 'description': desc,
                   'kind': 'constants' if path.startswith('constants/') else
                   ('base' if path in ('global.h', 'gba.h') else 'subsystem'),
                   'generated_by': 'tools/gencards.py' if path == 'constants/cards.h' else None,
                   'existing': path == 'global.h',
                   'replaces_legacy': [f'include/legacy/{k}' for k, v in LEGACY.items()
                                       if (v == path if isinstance(v, str) else path in v)],
                   'subsystems': set(), 'structs': [], 'enums': [], 'ram_globals': [], 'rom_data': [],
                   'local_rom_data': [], 'functions': [], 'includes': set(), 'forward_decls': set(),
                   'weight': 0.0}
        if path == 'constants/cards.h':
            H[path]['existing'] = False

    owners = {}

    def own(name, path, what):
        if name in owners and owners[name] != path:
            errors.append(f'{what} {name}: owned by both {owners[name]} and {path}')
        owners[name] = path

    # -------- structs
    for name, s in S.items():
        path = STRUCT_HOME.get(name)
        if path is None:
            errors.append(f'struct {name}: no owner in STRUCT_HOME')
            continue
        own(name, path, 'struct')
        locs = [{'unit': old2new.get(d['unit'], d['unit']), 'local_tags': d['local_tags']}
                for d in s.get('local_definitions') or []]
        fields = []
        for f in s['fields']:
            ft = FIELD_TYPE_FIXES.get((name, f['name']), f['type'])
            e = {'offset': f['offset'], 'bits': f.get('bits'), 'name': f['name'], 'type': ft,
                 'summary': f.get('summary'), 'confidence': f.get('confidence')}
            if ft != f['type']:
                e['type_in_types_json'] = f['type']
            fields.append(e)
        H[path]['structs'].append({
            'name': name, 'size': s['size'], 'globals': s.get('globals') or [], 'confidence': s.get('confidence'),
            'note': s.get('note'), 'fields': fields, 'unit_local_definitions': locs,
            'legacy_header': s.get('existing_header'),
            'applies_to': s.get('applies_to'),
            'layout_warnings': layout_warnings(name, s['size'], fields, S),
        })
        H[path]['subsystems'].add('types')
    for name, (path, repl, why) in LEGACY_ONLY_STRUCTS.items():
        if path:
            own(name, path, 'struct')
            H[path]['structs'].append({'name': name, 'size': None, 'globals': [], 'fields': None,
                                       'note': f'only in the legacy header ({why}); copy its layout',
                                       'legacy_header': 'include/legacy/' + ('duel.h' if path == 'duel.h'
                                                                             else 'duel_ui.h'),
                                       'unit_local_definitions': []})
    for name in STRUCT_HOME:
        if name not in S and name not in LEGACY_ONLY_STRUCTS:
            errors.append(f'STRUCT_HOME has {name}, which is not in types.json')

    # -------- enums
    for name, e in E.items():
        path = ENUM_HOME.get(name)
        if path is None:
            errors.append(f'enum {name}: no owner in ENUM_HOME')
            continue
        own(name, path, 'enum')
        H[path]['enums'].append({
            'name': name, 'values': len(e['values']), 'confidence': e.get('confidence'),
            'context': e.get('context'),
            'used_by_units': sorted({old2new.get(p, p) for p in e.get('proposed_by') or []}),
            'note': ('generated from assets (tools/gencards.py); the types.json CARDNO_* names are aliases'
                     if name == 'CardNumber' else None),
        })
    for name in ENUM_HOME:
        if name not in E:
            errors.append(f'ENUM_HOME has {name}, which is not in types.json')

    tagmap, tagmap_any = {}, collections.defaultdict(set)
    for name_, s_ in S.items():
        for d_ in s_.get('local_definitions') or []:
            for tag in d_['local_tags']:
                tagmap[(old2new.get(d_['unit'], d_['unit']), tag)] = name_
                tagmap_any[tag].add(name_)

    # -------- globals (RAM and ROM): canonical types
    struct_of_global = {}
    for name, s in S.items():
        for g in s.get('globals') or []:
            struct_of_global.setdefault(g, name)
    prop_types = collections.defaultdict(collections.Counter)
    import glob
    for f in glob.glob('build/names/*.json'):
        if f.endswith(('types.json', 'prototypes.json')):
            continue
        d = json.load(open(f))
        for x in d.get('globals') or []:
            if x.get('type') and clean_type(x['type']):
                prop_types[x['name']][clean_type(x['type'])] += 1
    gdecl = pdb['globals']
    for name, info in final.items():
        if info['kind'] not in ('ram', 'rom'):
            continue
        decl = gdecl.get(name)
        units = sorted({d['unit'] for d in decl['decls']}) if decl else []
        declared_as = decl['types'] if decl else {}
        st = struct_of_global.get(name)
        if info['kind'] == 'ram':
            if st:
                canon = None
                for t_, _ in prop_types[name].most_common():
                    if re.match(rf'^struct {st}\b', t_):
                        canon = t_
                        break
                canon = canon or f'struct {st}'
            else:
                canon = (prop_types[name].most_common(1)[0][0] if prop_types[name] else
                         (max(declared_as, key=declared_as.get) if declared_as else None))
        else:
            canon = None
            if declared_as:
                consts = {k: v for k, v in declared_as.items() if k.startswith('const')}
                pool = consts or declared_as
                canon = max(pool, key=pool.get)
                if not canon.startswith('const'):
                    canon = 'const ' + canon
        unres = []
        if name in GLOBAL_TYPE:
            canon = GLOBAL_TYPE[name]
        if canon:
            canon, unres = translate_tags(canon, units[0] if len(units) == 1 else None, tagmap, tagmap_any)
        path = GLOBAL_HOME.get(name)
        if path is None:
            bare = re.sub(r'^gStr|^g(?=[A-Z])', '', name)
            path = next((h for rx, h in GLOBAL_RULES if re.match(rx, bare)), None)
        if path is None:
            path = rule_header(info['sub'], name)
        entry = {'name': name, 'addr': info['addr'], 'canonical_type': canon, 'declared_as': declared_as,
                 'declared_by_units': units, 'summary': info['summary'][:240], 'confidence': info['confidence']}
        if unres:
            entry['unresolved_struct_tags'] = unres
        if name in GLOBAL_TYPE and GLOBAL_TYPE[name] == 'struct DuelCard[]':
            entry['type_note'] = GLOBAL_TYPE_NOTE
        if canon and declared_as:
            entry['views_differ'] = sorted(k for k in declared_as if k.replace('const ', '') != canon.replace(
                'const ', ''))
        if info['kind'] == 'ram' and name in UNIT_LOCAL_ALIASES:
            entry['unit'] = units[0] if units else None
            entry['note'] = UNIT_LOCAL_ALIASES[name]
            H[path].setdefault('local_ram_aliases', []).append(entry)
        elif info['kind'] == 'ram':
            own(name, path, 'global')
            H[path]['ram_globals'].append(entry)
        elif len(units) >= 2:
            own(name, path, 'global')
            H[path]['rom_data'].append(entry)
        else:
            entry['unit'] = units[0] if units else None
            H[path]['local_rom_data'].append({'name': name, 'addr': info['addr'], 'unit': entry['unit'],
                                              'declared_as': declared_as})
        H[path]['subsystems'].add(info['sub'])

    # -------- functions
    unit_sub = collections.defaultdict(collections.Counter)
    for name, f in funcs.items():
        if name in final:
            unit_sub[f['unit']][final[name]['sub']] += 1
    for name, f in sorted(funcs.items(), key=lambda kv: kv[1]['addr']):
        if name in STATIC_FUNCTIONS:      # file-local definitions: no prototype in any header
            continue
        info = final.get(name)
        sub = info['sub'] if info else (unit_sub[f['unit']].most_common(1)[0][0] if unit_sub[f['unit']] else None)
        if f['unit'] in ('sdk/libagbsyscall',):
            path = 'gba.h'
        elif f['unit'] == 'sdk/agb_sram':
            path = 'save.h'
        elif f['unit'] == 'sound_mixer_arm':
            path = 'sound.h'
        elif f['unit'] == 'crt0':
            path = 'main.h'
        elif sub is None:
            errors.append(f'function {name}: no subsystem')
            continue
        else:
            path = rule_header(sub, name, f['unit'])
        own(name, path, 'function')
        d = pdb['functions'].get(name)
        pp = protos_prop.get(name)
        entry = {'name': name, 'addr': f['addr'], 'unit': f['unit'], 'mode': f['mode'],
                 'summary': (info or {}).get('summary', '')[:300] or None,
                 'confidence': (info or {}).get('confidence')}
        if d:
            entry['proto'] = d['proto']
            if d.get('kr'):
                entry['kr'] = True
            hp, unresolved = translate_tags(d.get('hproto') or d['proto'], f['unit'], tagmap, tagmap_any)
            if hp != d['proto']:
                entry['header_proto'] = hp
            if unresolved:
                entry['unresolved_struct_tags'] = unresolved
            names_now = [p['name'] for p in d['params']]
            if pp and pp.get('params') and len(pp['params']) == len(d['params']):
                pn = [re.split(r'[\s*]+', x.strip())[-1].strip('[]') for x in pp['params']]
                pn = [re.sub(r'\[.*$', '', x) for x in pn]
                if all(re.match(r'^[A-Za-z_]\w*$', x) for x in pn) and pn != names_now:
                    entry['param_names'] = pn
            if pp and pp.get('comments'):
                entry['comments'] = pp['comments']
            v = [x for x in d['views'] if x['status'] in ('abi', 'unprototyped', 'arity')]
            if v:
                entry['units_with_abi_views'] = sorted({x['unit'] for x in v})
            tv = [x for x in d['views'] if x['status'] == 'type']
            if tv:
                entry['units_with_type_views'] = sorted({x['unit'] for x in tv})
        else:
            a_ = pdb['asm_functions'].get(name, {})
            entry['asm'] = True
            entry['proto'] = None
            entry['declared_as'] = sorted({x['proto'] for x in a_.get('views', [])})
            if pp:
                entry['proposed'] = f"{pp.get('returns')} {name}({', '.join(pp.get('params') or ['void'])})"
        H[path]['functions'].append(entry)
        if sub:
            H[path]['subsystems'].add(sub)

    # -------- includes / forward declarations
    for path, h in H.items():
        deps, fwd = set(), set()
        for s in h['structs']:
            for f in s['fields'] or []:
                for tag in by_value_structs(f['type']):
                    deps.add(tag)
                for tag in ptr_structs(f['type']):
                    fwd.add(tag)
        for g in h['ram_globals'] + h['rom_data']:
            if g['canonical_type']:
                for tag in by_value_structs(g['canonical_type']):
                    deps.add(tag)
        for fn in h['functions']:
            p = fn.get('header_proto') or fn.get('proto') or ''
            for tag in STRUCT_REF.findall(p):
                fwd.add(tag[1])
        own_structs = {s['name'] for s in h['structs']}
        inc = set()
        for tag in deps:
            o = STRUCT_HOME.get(tag) or (LEGACY_ONLY_STRUCTS.get(tag, (None,))[0])
            if o and o != path:
                inc.add(o)
        h['includes'] = sorted(inc)
        h['forward_decls'] = sorted(t for t in fwd - own_structs - deps
                                    if t in STRUCT_HOME and STRUCT_HOME[t] != path)
        h['unknown_struct_tags'] = sorted(t for t in (fwd | deps) - own_structs if t not in STRUCT_HOME
                                          and t not in LEGACY_ONLY_STRUCTS)
        h['subsystems'] = sorted(h['subsystems'] - {'types'})
    # cycle check + tiers
    tiers, done = {}, set()
    remaining = set(H)
    level = 0
    while remaining:
        ready = {p for p in remaining if all(i in done for i in H[p]['includes'])}
        if not ready:
            errors.append(f'include cycle among: {sorted(remaining)}')
            break
        for p in ready:
            tiers[p] = level
        done |= ready
        remaining -= ready
        level += 1
    if sorted(INCLUDE_ORDER) != sorted(H):
        errors.append(f'INCLUDE_ORDER and HEADERS differ: {sorted(set(INCLUDE_ORDER) ^ set(H))}')
    for p, h in H.items():
        h['may_include'] = [f'include/{x}' for x in INCLUDE_ORDER[:INCLUDE_ORDER.index(p)]] if p in INCLUDE_ORDER \
            else []
        for inc in h['includes']:
            if p in INCLUDE_ORDER and inc in INCLUDE_ORDER and INCLUDE_ORDER.index(inc) > INCLUDE_ORDER.index(p):
                errors.append(f'{p} needs {inc}, which comes later in INCLUDE_ORDER (cycle risk)')
        h['includes'] = [f'include/{x}' for x in h['includes']]
    for p, h in H.items():
        h['tier'] = tiers.get(p)
        h['weight'] = round(len(h['functions']) * (0.25 if p == 'effect_handlers.h' else 0.5)
                            + sum(4 + 0.5 * len(s['fields'] or []) for s in h['structs'])
                            + sum(1 + 0.05 * e['values'] for e in h['enums'] if e['name'] != 'CardNumber')
                            + (5 if any(e['name'] == 'CardNumber' for e in h['enums']) else 0)
                            + 0.5 * (len(h['ram_globals']) + len(h['rom_data'])), 1)
        h['counts'] = {'structs': len(h['structs']), 'enums': len(h['enums']), 'functions': len(h['functions']),
                       'ram_globals': len(h['ram_globals']), 'rom_data': len(h['rom_data'])}

    # legacy renames
    ren, err = legacy_renames(S)
    for tag, r in ren.items():
        path = STRUCT_HOME.get(tag)
        if path:
            for s in H[path]['structs']:
                if s['name'] == tag:
                    s['legacy_renames'] = r['renames']
                    s['legacy_header'] = r['legacy_header']
    if err:
        errors.append('legacy renames not computed: ' + err)

    # notes: HEADER_NOTES, types.json notes (by keyword), alias folds (by target global)
    kw = [('DuelState', 'duel.h'), ('DuelZone', 'duel.h'), ('ChainEntry', 'chain.h'), ('ChainState', 'chain.h'),
          ('gTextBox', 'text_box.h'), ('gCalendar', 'calendar.h'), ('gOpponentSelect', 'campaign.h'),
          ('SaveData', 'save.h'), ('Card type values', 'constants/card_stats.h'), ('DuelCmd operands', 'duel_cmd.h'),
          ('Non-EDS effect keys', 'constants/cards.h')]
    for p, h in H.items():
        h['notes'] = list(HEADER_NOTES.get(p, []))
    for n in types.get('notes', []):
        for k, p in kw:
            if k in n and n not in H[p]['notes']:
                H[p]['notes'].append('types.json: ' + n)
    unattached = []
    for a_ in types.get('alias_folds', []):
        tgt = (a_['fold_to'] or [''])[0]
        m = re.search(r'\b(g[A-Z]\w*)', ' '.join(a_['fold_to']))
        gname = {'gDialogueScene': 'gBustup', 'gActionLists': 'gChain'}.get(m.group(1), m.group(1)) if m else None
        o = owners.get(gname) if gname else None
        rec = {'addr': a_['addr'], 'symbol': a_['symbol'], 'fold_to': a_['fold_to'],
               'units': sorted({old2new.get(u, u) for u in a_['units']}), 'summary': a_['summary'][:200]}
        if o:
            H[o].setdefault('alias_folds', []).append(rec)
        else:
            unattached.append(rec)
        del tgt

    groups = []
    for g, desc in GROUPS.items():
        hs = [p for p, h in H.items() if h['group'] == g]
        groups.append({'name': g, 'description': desc, 'headers': [f'include/{p}' for p in hs],
                       'weight': round(sum(H[p]['weight'] for p in hs), 1),
                       'functions': sum(len(H[p]['functions']) for p in hs),
                       'structs': sum(len(H[p]['structs']) for p in hs),
                       'enums': sum(len(H[p]['enums']) for p in hs),
                       'subsystems': sorted({s for p in hs for s in H[p]['subsystems']})})
    for p, h in H.items():
        if h['group'] not in GROUPS:
            errors.append(f'{p}: unknown group {h["group"]}')
    if errors:
        for e in errors:
            print('ERROR', e, file=sys.stderr)
        if any('cycle' in e or 'owned by both' in e or 'no owner' in e for e in errors):
            sys.exit(1)
    return {
        'generated': datetime.date.today().isoformat(), 'tool': 'tools/headerplan.py',
        'inputs': ['build/names/types.json', 'build/names/final.txt', 'build/names/prototypes.json',
                   'build/readability/protos.json', 'build/readability/unit_names.tsv', 'config/functions.tsv'],
        'notes': NOTES,
        'h0_commands': H0_COMMANDS,
        'include_order': [f'include/{p}' for p in INCLUDE_ORDER],
        'include_rule': 'A header includes global.h, the headers in its "includes" (by-value struct uses, required) '
                        'and optionally other headers listed in its "may_include" (only earlier ones in include_order); '
                        'pointer-only uses get forward declarations. constants/*.h include nothing.',
        'groups': groups,
        'headers': {p: h for p, h in H.items()},
        'owners': {k: f'include/{v}' for k, v in sorted(owners.items())},
        'alias_folds_unattached': unattached,
        'errors': errors,
    }


def summary(plan):
    print(f"{len(plan['headers'])} headers, {len(plan['owners'])} owned names")
    for g in plan['groups']:
        print(f"  {g['name']:11s} w={g['weight']:6.1f} fn={g['functions']:4d} st={g['structs']:3d} "
              f"en={g['enums']:3d}  {' '.join(h.replace('include/', '') for h in g['headers'])}")
    for p, h in plan['headers'].items():
        if h['includes'] or h['unknown_struct_tags']:
            print(f"  {p:22s} tier {h['tier']} includes {h['includes']}"
                  + (f" UNKNOWN {h['unknown_struct_tags']}" if h['unknown_struct_tags'] else ''))
    if plan['errors']:
        print(f"{len(plan['errors'])} errors (see 'errors')")


