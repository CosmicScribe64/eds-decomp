def rule_header(sub, name, unit=None):
    bare = re.sub(r'^gStr|^g(?=[A-Z])', '', name)
    for s, rx, h in NAME_RULES:
        if s not in ('*', sub):
            continue
        if rx.startswith('^@unit:'):
            if unit and re.match(rx[7:], unit):
                return h
            continue
        if re.match(rx, bare) or re.match(rx, name):
            return h
    return SUB_DEFAULT[sub]


STRUCT_REF = re.compile(r'\b(struct|union)\s+(\w+)')


def by_value_structs(ctype):
    """Struct tags used by value in a C type string (members, arrays); pointers and function pointers excluded."""
    t = re.sub(r'\([^()]*\)', lambda m: '' if '*' in m.group(0) else m.group(0), ctype)  # drop (...) groups w/ ptr
    out = []
    for m in STRUCT_REF.finditer(ctype):
        rest = ctype[m.end():].lstrip()
        if rest.startswith('*'):
            continue
        # inside a function-pointer parameter list?
        before = ctype[:m.start()]
        if before.count('(') > before.count(')'):
            continue
        out.append(m.group(2))
    del t
    return out


def ptr_structs(ctype):
    out = []
    for m in STRUCT_REF.finditer(ctype):
        if m.group(2) not in by_value_structs(ctype):
            out.append(m.group(2))
    return out


CTYPE_RE = re.compile(r'^void\s*\(\*\s*\[[^\]]*\]\)\s*\(void\)'
                      r'|^(?:(?:const|volatile)\s+)*(?:struct\s+\w+|union\s+\w+|unsigned\s+\w+|[us]8|[us]16|[us]32|'
                      r'vu8|vu16|vu32|bool8|bool32|char|short|int|void)(?:\s*\*)*(?:\s*\[[^\]]*\])*')


def clean_type(s):
    """Leading C type of a proposal's type text ("struct DuelCard[80] per player, ..." -> "struct DuelCard[80]");
    None when the text does not start with a type."""
    s = (s or '').strip()
    m = CTYPE_RE.match(s)
    return m.group(0).strip() if m else None


def translate_tags(proto, unit, tagmap, tagmap_any):
    """Replace the unit-local struct tags of a definition's prototype with the canonical struct names."""
    unresolved = []

    def rep(m):
        tag = m.group(2)
        if (unit, tag) in TAG_FIXES:
            return f'struct {TAG_FIXES[(unit, tag)]}'
        if tag in LEGACY_ONLY_STRUCTS:
            path_, repl, _ = LEGACY_ONLY_STRUCTS[tag]
            if path_ is None and repl and re.match(r'^\w+$', repl):    # renamed: SoundPcmVoice -> SoundPcmChannel
                return f'struct {repl}'
            return m.group(0)
        if tag in STRUCT_HOME:
            return m.group(0)
        new = tagmap.get((unit, tag)) or TAG_FIXES.get((unit, tag))
        if new is None and unit is None:
            new = next((v for (u, t), v in TAG_FIXES.items() if t == tag), None)
        if new is None and len(tagmap_any.get(tag, ())) == 1:
            new = next(iter(tagmap_any[tag]))
        if new is None:
            unresolved.append(tag)
            return m.group(0)
        return f'struct {new}'
    out = STRUCT_REF.sub(rep, proto)
    return out, sorted(set(unresolved))


